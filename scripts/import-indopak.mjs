// Imports an IndoPak (Nastaleeq) Quran text and its font after you have read
// and accepted the licence of both on their download pages.
// Run: node scripts/import-indopak.mjs <text.json> <font.ttf> "<licence as stated by the source>"
// The text must hold every ayah in order: 114 suras, 6236 ayahs. It is stored unchanged.

import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { readIndoPak } from './content-lib.mjs';

const [textPath, fontPath, licence] = process.argv.slice(2);
if (!textPath || !fontPath || !licence) {
  console.error('Usage: node scripts/import-indopak.mjs <text.json> <font.ttf> "<licence>"');
  process.exit(1);
}
const uthmani = JSON.parse(await readFile('src/data/quran/quran.json', 'utf8'));
if (uthmani.suras.length !== 114) throw new Error('Run scripts/fetch-content.mjs first (needs sura lengths).');
const suras = readIndoPak(JSON.parse(await readFile(textPath, 'utf8')), uthmani.suras.map((s) => s.ayahs.length));
await writeFile('src/data/quran/quran-indopak.json', JSON.stringify({ source: textPath.split('/').pop(), licence, suras }));
await mkdir('assets/fonts', { recursive: true });
await copyFile(fontPath, 'assets/fonts/indopak-nastaleeq.ttf');
await writeFile('src/data/quran/fonts.ts', `// Generated by scripts/import-indopak.mjs. Do not edit by hand.
export const INDOPAK_FONT: number | null = require('../../../assets/fonts/indopak-nastaleeq.ttf');
`);
console.log('IndoPak text imported: 114 suras, 6236 ayahs.');
